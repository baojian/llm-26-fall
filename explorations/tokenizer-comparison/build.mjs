/* Publish the measured teaching tables and page from the same offline report. */
import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const topic = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(topic, '../..');
const require = createRequire(path.join(root, 'slides/package.json'));
const MarkdownIt = require('markdown-it');
let input = '';
for await (const chunk of process.stdin) input += chunk;
const report = JSON.parse(input);
assert.equal(report.schema_version, 1);
const names = Object.keys(report.tokenizers);
assert.equal(names.length, 6);
const statuses = { exact: 'Exact', 'nfc-equivalent': 'NFC', 'unknown-tokens': 'Unknown', 'text-changed': 'Changed' };
const escape = value => String(value).replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;');
const number = value => value.toLocaleString('en-US');
const vocabulary = [
  '| Tokenizer | Algorithm | Base entries | All entries | Special entries¹ | Highest ID + 1 | Sources and notes |',
  '| --- | --- | ---: | ---: | ---: | ---: | --- |',
  ...names.map(name => {
    const t = report.tokenizers[name];
    return `| \`${name}\` | ${t.algorithm} | ${number(t.base_vocabulary_entries)} | ${number(t.vocabulary_entries)} | ${number(t.special_token_entries)} | ${number(t.highest_token_id_plus_one)} | [Pinned artifact](${t.source}); ${t.vocabulary_entries < t.highest_token_id_plus_one ? 'IDs have gaps' : 'contiguous ID capacity'} |`;
  }),
].join('\n');
const counts = [
  `| Example | ${names.map(name => `\`${name}\``).join(' | ')} |`,
  `| --- | ${names.map(() => '---:').join(' | ')} |`,
  ...report.cases.map(c => `| \`${c.id}\` | ${names.map(n => `${c.observed[n].token_count} · ${statuses[c.observed[n].fidelity]}`).join(' | ')} |`),
].join('\n');
const examples = report.cases.map(c => `### ${c.id}\n\n${c.question}\n\nInput as a JSON string (tabs and newlines escaped):\n\n\`\`\`json\n${JSON.stringify(c.text)}\n\`\`\`\n`).join('\n');
const provenance = Object.entries(report.provenance.artifacts).map(([name, spec]) => `- \`${name}\`: revision \`${spec.revision}\`; SHA-256 \`${spec.sha256}\`.`).join('\n');
const results = `# Measured tokenizer comparisons

Generated by \`run.py build\` from [the pinned manifest](tokenizers.json) and
[32 authored inputs](inputs.json). Read the [analysis](README.md) or
[explore the pipelines](index.html). These small examples are not a corpus benchmark.

## Vocabulary

${vocabulary}

¹ Special entries are a subset of all entries. They can already be in the base
vocabulary: do not add these columns together. All entries include added tokens.
Allocated embedding rows and embedding width were not measured.

## Token counts and decoding

Each cell gives token count and decoding outcome. **Exact** means identical to
the original input; **NFC** means different but canonically equivalent;
**Unknown** means a non-exact decoding with unknown-token IDs; **Changed**
means another non-exact transformation. Counts from these outcomes should not
be pooled into a compression ranking.

${counts}

## Inputs and questions

${examples}
## Reproduction evidence

Policy: ${report.provenance.policy}.

Runtime packages: ${Object.entries(report.provenance.runtime_versions).map(([name, version]) => `\`${name} ${version}\``).join(', ')}.

Diagnostic NFC comparison: Python Unicode database \`${report.provenance.unicode_database_version}\`.

- Manifest SHA-256: \`${report.provenance.manifest_sha256}\`.
- Canonical inputs SHA-256: \`${report.provenance.inputs_sha256}\`.
- Measurement runner SHA-256: \`${report.provenance.runner_sha256}\`.

${provenance}

The raw report, including every token ID and piece, is regenerated under
ignored \`workspace/tokenizer-comparison/report.json\`. The interactive page
embeds those observations for offline inspection.
`;

const md = new MarkdownIt({ html: false, linkify: false, typographer: false });
const headingRule = md.renderer.rules.heading_open;
md.renderer.rules.heading_open = (tokens, idx, options, env, self) => {
  const title = tokens[idx + 1].content;
  tokens[idx].attrSet('id', `${env.prefix}-${title.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/-$/, '')}`);
  return headingRule ? headingRule(tokens, idx, options, env, self) : self.renderToken(tokens, idx, options);
};
md.renderer.rules.table_open = () => '<div class="table-scroll" tabindex="0" role="region" aria-label="Scrollable data table"><table>\n';
md.renderer.rules.table_close = () => '</table></div>\n';
const readme = await readFile(path.join(topic, 'README.md'), 'utf8');
const analysis = md.render(readme.replace(/^# .*\n/, ''), { prefix: 'analysis' });
const measured = md.render(results.replace(/^# .*\n/, ''), { prefix: 'results' });
const encoded = JSON.stringify(report).replaceAll('<', '\\u003c').replaceAll('\u2028', '\\u2028').replaceAll('\u2029', '\\u2029');
const options = names.map(n => `<option value="${escape(n)}">${escape(n)}</option>`).join('');
const groups = [...new Set(report.cases.map(c => c.group))];
const caseOptions = groups.map(group => `<optgroup label="${escape(group)}">${report.cases.filter(c => c.group === group).map(c => `<option value="${escape(c.id)}">${escape(c.id)}</option>`).join('')}</optgroup>`).join('');
const html = `<!doctype html>
<!-- Generated by explorations/tokenizer-comparison/run.py build. -->
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">
<title>The same text, six tokenizers · Course explorations</title>
<meta name="description" content="Explore 32 measured examples across six pinned tokenizers: vocabulary, boundaries, Unicode, coverage, and decoding.">
<link rel="stylesheet" href="style.css"><link rel="stylesheet" href="../../assets/course-language.css">
<script src="../../assets/course-language.js" defer></script><script src="explorer.js" defer></script></head>
<body><a class="skip" href="#content">Skip to the exploration</a>
<header><nav aria-label="Course navigation"><a href="../../index.html" data-en="Course" data-zh="课程主页">Course</a>
<a href="../index.html" data-en="Explorations" data-zh="专题探索">Explorations</a>
<a href="../../slides/lecture-01/" data-en="Lecture 01" data-zh="第 1 讲">Lecture 01</a>
<button type="button" id="print" data-en="Print" data-zh="打印">Print</button>
<div class="lang-toggle" role="group" aria-label="Language / 语言"><button type="button" data-lang="en" aria-pressed="true">EN</button><button type="button" data-lang="zh" aria-pressed="false">中文</button></div></nav></header>
<main id="content"><p class="eyebrow">EXPLORATION 01 · TEXT → TOKENS</p>
<h1>The same text,<br>six tokenizers.</h1>
<p class="intro">Inspect where text is split, what a vocabulary contains, and what survives decoding.</p>
<p class="scope">6 pinned tokenizers · 32 authored examples · CPU measurements · English reading material</p>
<nav class="jump" aria-label="On this page"><a href="#explore">Explore examples</a><a href="#analysis">Read the analysis</a><a href="#measurements">All measurements</a><a href="#analysis-reproduce-or-explore-another-input">Reproduce</a></nav>
<section id="explore" aria-labelledby="explore-title"><div class="section-heading"><span>01 / INSPECT</span><h2 id="explore-title">Follow the same input through two pipelines</h2></div>
<p>Choose a measured example. All six counts appear below; choose any two tokenizers to inspect the stages. These observations use ordinary text without chat formatting or automatic special tokens.</p>
<div class="controls"><label for="case" data-en="Example" data-zh="示例">Example</label><select id="case">${caseOptions}</select>
<label for="left" data-en="Left tokenizer" data-zh="左侧分词器">Left tokenizer</label><select id="left">${options}</select>
<label for="right" data-en="Right tokenizer" data-zh="右侧分词器">Right tokenizer</label><select id="right">${options}</select></div>
<p id="question" class="question" aria-live="polite"></p><div class="input-box"><strong>Original input · JSON notation</strong><pre id="input"></pre><p id="input-size"></p></div>
<figure><figcaption>Token count and decoding outcome · same input, all six tokenizers</figcaption><div id="counts" class="counts"></div></figure>
<p class="legend"><strong>Read the outcome with the count.</strong> Exact: unchanged string. NFC equivalent: canonical Unicode equivalent. Unknown tokens: content was replaced. Text changed: another transformation. A low count alone is not a quality score.</p>
<div class="pipelines" id="pipelines"></div>
<p class="caption">The pre-tokenizer preview runs on normalized text in isolation. Added-token matching may happen earlier, so the preview is not a complete encoding trace. IDs and final pieces come from the actual tokenizer.</p>
<noscript><p>The inspector needs JavaScript. The complete analysis and measured tables below remain readable.</p></noscript></section>
<section id="analysis" class="article" lang="en"><div class="section-heading"><span>02 / EXPLAIN</span><h2>What the comparisons show</h2></div>${analysis}</section>
<section id="measurements" class="article" lang="en"><div class="section-heading"><span>03 / VERIFY</span><h2>Measured reference</h2></div>${measured}</section>
<footer>Fudan University · NLP and LLMs · Fall 2026<br>Instructor-authored teaching exploration. <a href="README.md">Editable analysis</a> · <a href="results.md">Measured tables</a> · <a href="tokenizers.json">Sources</a></footer>
</main><script id="measurements-data" type="application/json">${encoded}</script></body></html>
`;

for (const [name, content] of [['results.md', results], ['index.html', html]]) {
  const target = path.join(topic, name);
  if (process.argv.includes('--check')) {
    assert.equal(await readFile(target, 'utf8'), content, `${name} is stale; run the build command.`);
    console.log(`${name}: reproducible`);
  } else {
    await writeFile(target, content);
    console.log(`Built ${path.relative(root, target)}`);
  }
}
